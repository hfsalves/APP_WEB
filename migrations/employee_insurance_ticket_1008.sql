IF OBJECT_ID('dbo.MOD_OBJETOS', 'U') IS NOT NULL
BEGIN
    DECLARE @RhModule varchar(25);
    SELECT TOP 1 @RhModule = MODSTAMP
    FROM dbo.MODULOS
    WHERE UPPER(LTRIM(RTRIM(ISNULL(CODIGO, '')))) = 'RH'
      AND ISNULL(ATIVO, 0) = 1;

    IF @RhModule IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM dbo.MOD_OBJETOS
        WHERE MODSTAMP=@RhModule AND OBJKEY='MENU:EMPINSURANCEMENU00000001'
    )
    BEGIN
        INSERT INTO dbo.MOD_OBJETOS
            (MODOBJSTAMP, MODSTAMP, TIPO, OBJKEY, OBJNOME, OBJROTA, MENUSTAMP,
             ORDEM, ATIVO, DTCRI, USERCRIACAO, USERALTERACAO)
        VALUES
            (LEFT(REPLACE(CONVERT(varchar(36), NEWID()), '-', ''), 25), @RhModule,
             'MENU', 'MENU:EMPINSURANCEMENU00000001', 'Mapa para Seguradora',
             '/dashboard/mapa-seguradora', 'EMPINSURANCEMENU00000001',
             612, 1, GETDATE(), 'codex', '');
    END;

    UPDATE dbo.MOD_OBJETOS
       SET OBJNOME='Mapa para Seguradora', OBJROTA='/dashboard/mapa-seguradora',
           MENUSTAMP='EMPINSURANCEMENU00000001', ORDEM=612, ATIVO=1,
           DTALT=GETDATE(), USERALTERACAO='codex'
     WHERE OBJKEY='MENU:EMPINSURANCEMENU00000001';
END;

UPDATE A
SET CONSULTAR=1, EDITAR=1, USSTAMP=U.USSTAMP
FROM dbo.ACESSOS A
JOIN dbo.US U ON LOWER(LTRIM(RTRIM(U.LOGIN)))=LOWER(LTRIM(RTRIM(A.UTILIZADOR)))
WHERE UPPER(LTRIM(RTRIM(ISNULL(A.TABELA, ''))))='PE_SEGURO'
  AND (LOWER(LTRIM(RTRIM(U.LOGIN)))='pedro' OR ISNULL(U.ADMIN,0)=1 OR ISNULL(U.DEV,0)=1);

INSERT INTO dbo.ACESSOS
    (ACESSOSSTAMP, UTILIZADOR, TABELA, CONSULTAR, INSERIR, EDITAR, ELIMINAR, USSTAMP)
SELECT
    LEFT(REPLACE(CONVERT(varchar(36), NEWID()), '-', ''), 25), U.LOGIN,
    'PE_SEGURO', 1, 0, 1, 0, U.USSTAMP
FROM dbo.US U
WHERE ISNULL(U.INATIVO,0)=0
  AND (LOWER(LTRIM(RTRIM(U.LOGIN)))='pedro' OR ISNULL(U.ADMIN,0)=1 OR ISNULL(U.DEV,0)=1)
  AND NOT EXISTS (
      SELECT 1 FROM dbo.ACESSOS A
      WHERE LOWER(LTRIM(RTRIM(A.UTILIZADOR)))=LOWER(LTRIM(RTRIM(U.LOGIN)))
        AND UPPER(LTRIM(RTRIM(ISNULL(A.TABELA, ''))))='PE_SEGURO'
  );

COMMIT TRANSACTION;
