IF OBJECT_ID('dbo.GUESTSPA_EMPLOYEE_PROFESSION', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.GUESTSPA_EMPLOYEE_PROFESSION (
        PROFSTAMP varchar(25) NOT NULL CONSTRAINT PK_GUESTSPA_EMPLOYEE_PROFESSION PRIMARY KEY,
        CODIGO varchar(20) NOT NULL,
        DESCRICAO varchar(200) NOT NULL CONSTRAINT DF_GSEMPPROF_DESCRICAO DEFAULT (''),
        ATIVO bit NOT NULL CONSTRAINT DF_GSEMPPROF_ATIVO DEFAULT (1),
        DTALTERACAO_UTC datetime2(0) NOT NULL CONSTRAINT DF_GSEMPPROF_DTALT DEFAULT (SYSUTCDATETIME()),
        UTILIZADOR varchar(60) NOT NULL CONSTRAINT DF_GSEMPPROF_USER DEFAULT ('')
    );
    CREATE UNIQUE INDEX UX_GSEMPPROF_CODIGO ON dbo.GUESTSPA_EMPLOYEE_PROFESSION (CODIGO);
