SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID('dbo.TRANSFERS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TRANSFERS (
        TRANSFERSTAMP varchar(25) NOT NULL PRIMARY KEY,
        RSSTAMP varchar(25) NOT NULL,
        RESERVA varchar(60) NOT NULL,
        ALOJAMENTO varchar(120) NULL,
        ORIGEM varchar(20) NOT NULL,
        DATA_CHEGADA date NOT NULL,
        HORA_CHEGADA varchar(5) NOT NULL,
        NUM_VOO varchar(20) NULL,
        TEM_PARTIDA bit NOT NULL CONSTRAINT DF_TRANSFERS_TEM_PARTIDA DEFAULT 0,
        DATA_PARTIDA date NULL,
        HORA_PARTIDA varchar(5) NULL,
        VALOR decimal(10,2) NOT NULL CONSTRAINT DF_TRANSFERS_VALOR DEFAULT 30,
        ESTADO varchar(20) NOT NULL CONSTRAINT DF_TRANSFERS_ESTADO DEFAULT 'PENDENTE',
        EMAIL_ID bigint NULL,
        DTCRI datetime NOT NULL CONSTRAINT DF_TRANSFERS_DTCRI DEFAULT GETDATE(),
        DTALT datetime NULL
    );
    CREATE INDEX IX_TRANSFERS_RESERVA ON dbo.TRANSFERS (RESERVA, DTCRI DESC);
END;

IF COL_LENGTH('dbo.TRANSFERS', 'MORADA') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD MORADA varchar(300) NULL;
IF COL_LENGTH('dbo.TRANSFERS', 'NOME_HOSPEDE') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD NOME_HOSPEDE varchar(200) NULL;
IF COL_LENGTH('dbo.TRANSFERS', 'NUM_PESSOAS') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD NUM_PESSOAS int NOT NULL CONSTRAINT DF_TRANSFERS_NUM_PESSOAS DEFAULT 0;
IF COL_LENGTH('dbo.TRANSFERS', 'CONTACTO_TELEF') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD CONTACTO_TELEF varchar(50) NULL;
IF COL_LENGTH('dbo.TRANSFERS', 'EMAIL_HOSPEDE') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD EMAIL_HOSPEDE varchar(255) NULL;
IF COL_LENGTH('dbo.TRANSFERS', 'MOTORISTA_CONTACTO') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD MOTORISTA_CONTACTO varchar(50) NULL;
IF COL_LENGTH('dbo.TRANSFERS', 'MOTORISTA_EMAIL') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD MOTORISTA_EMAIL varchar(255) NULL;
IF COL_LENGTH('dbo.TRANSFERS', 'REQUEST_KEY') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD REQUEST_KEY varchar(64) NULL;
IF COL_LENGTH('dbo.TRANSFERS', 'REQUEST_HASH') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD REQUEST_HASH char(64) NULL;
IF COL_LENGTH('dbo.TRANSFERS', 'EMAIL_ESTADO') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD EMAIL_ESTADO varchar(20) NOT NULL
        CONSTRAINT DF_TRANSFERS_EMAIL_ESTADO DEFAULT 'NAO_ENVIADO' WITH VALUES;
IF COL_LENGTH('dbo.TRANSFERS', 'EMAIL_ERRO') IS NULL
    ALTER TABLE dbo.TRANSFERS ADD EMAIL_ERRO nvarchar(1000) NULL;

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.TRANSFERS') AND name='UX_TRANSFERS_REQUEST_KEY')
    EXEC(N'CREATE UNIQUE INDEX UX_TRANSFERS_REQUEST_KEY ON dbo.TRANSFERS (REQUEST_KEY) WHERE REQUEST_KEY IS NOT NULL');
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.TRANSFERS') AND name='IX_TRANSFERS_REQUEST_HASH')
    EXEC(N'CREATE INDEX IX_TRANSFERS_REQUEST_HASH ON dbo.TRANSFERS (REQUEST_HASH, ESTADO, DTCRI DESC) WHERE REQUEST_HASH IS NOT NULL');

DECLARE @menustamp varchar(25);
SELECT TOP 1 @menustamp = MENUSTAMP FROM dbo.MENU WHERE TABELA = 'TRANSFERS';
IF @menustamp IS NULL
BEGIN
    SET @menustamp = LEFT(REPLACE(CONVERT(varchar(36), NEWID()), '-', ''), 25);
    INSERT INTO dbo.MENU (MENUSTAMP, ORDEM, NOME, TABELA, URL, ADMIN, ICONE, FORM, NOVO, INATIVO)
    VALUES (@menustamp, 206, 'Transfers', 'TRANSFERS', '/generic/view/TRANSFERS', 1, 'fa-taxi', '', 0, 0);
END;

UPDATE dbo.MENU
SET ORDEM = 206,
    NOME = 'Transfers',
    URL = '/generic/view/TRANSFERS',
    ADMIN = 1,
    ICONE = 'fa-taxi',
    INATIVO = 0
WHERE MENUSTAMP = @menustamp;

DECLARE @fields TABLE (NMCAMPO varchar(25), DESCRICAO varchar(60), TIPO varchar(18), ORDEM int, TAM int, LISTA bit, FILTRO bit, RONLY bit, OBRIGATORIO bit);
INSERT INTO @fields VALUES
 ('RESERVA','Reserva','TEXT',10,15,1,1,1,1), ('ALOJAMENTO','Alojamento','TEXT',20,20,1,1,1,0),
 ('ORIGEM','Percurso','TEXT',30,15,1,1,0,1), ('DATA_CHEGADA','Data do transfer','DATE',40,10,1,1,0,1),
 ('HORA_CHEGADA','Hora chegada','TEXT',50,8,1,0,0,1), ('NUM_VOO','N.º voo','TEXT',60,10,1,0,0,0),
 ('TEM_PARTIDA','Tem partida','BIT',70,8,1,1,0,0), ('DATA_PARTIDA','Data partida','DATE',80,10,1,1,0,0),
 ('HORA_PARTIDA','Hora partida','TEXT',90,8,1,0,0,0), ('VALOR','Valor','DECIMAL',100,8,1,0,1,1),
 ('ESTADO','Estado','TEXT',110,10,1,1,0,1), ('EMAIL_ID','Email','INT',120,10,0,0,1,0),
 ('MORADA','Morada','TEXT',130,24,0,0,1,0), ('NOME_HOSPEDE','Hóspede','TEXT',140,18,1,1,1,0),
 ('NUM_PESSOAS','N.º pessoas','INT',150,8,1,0,1,0), ('CONTACTO_TELEF','Telefone','TEXT',160,14,1,0,1,0),
 ('EMAIL_HOSPEDE','Email hóspede','TEXT',170,20,1,0,1,0), ('MOTORISTA_CONTACTO','Contacto motorista','TEXT',180,16,1,0,1,0),
 ('MOTORISTA_EMAIL','Email motorista','TEXT',190,20,1,0,1,0),
 ('EMAIL_ESTADO','Estado notificação','TEXT',200,14,1,1,1,0),
 ('EMAIL_ERRO','Erro notificação','MEMO',210,24,0,0,1,0);

MERGE dbo.CAMPOS AS T USING @fields AS S ON T.TABELA='TRANSFERS' AND T.NMCAMPO=S.NMCAMPO
WHEN MATCHED THEN UPDATE SET DESCRICAO=S.DESCRICAO,TIPO=S.TIPO,ORDEM=S.ORDEM,TAM=S.TAM,LISTA=S.LISTA,FILTRO=S.FILTRO,RONLY=S.RONLY,OBRIGATORIO=S.OBRIGATORIO,VISIVEL=1
WHEN NOT MATCHED THEN INSERT (CAMPOSSTAMP,ORDEM,NMCAMPO,DESCRICAO,TIPO,TABELA,LISTA,FILTRO,FILTRODEFAULT,ADMIN,RONLY,COMBO,VIRTUAL,VISIVEL,TAM,ORDEM_MOBILE,TAM_MOBILE,CONDICAO_VISIVEL,OBRIGATORIO)
VALUES (LEFT(REPLACE(CONVERT(varchar(36), NEWID()), '-', ''),25),S.ORDEM,S.NMCAMPO,S.DESCRICAO,S.TIPO,'TRANSFERS',S.LISTA,S.FILTRO,'',0,S.RONLY,'','',1,S.TAM,S.ORDEM,S.TAM,'',S.OBRIGATORIO);

COMMIT TRANSACTION;
