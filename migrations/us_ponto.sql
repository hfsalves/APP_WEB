        LISTA_MOBILE_ITALIC, LISTA_MOBILE_SHOW_LABEL, LISTA_MOBILE_LABEL,
        PROPRIEDADES
    )
    VALUES
    (
        LEFT(CONVERT(varchar(36), NEWID()), 25), 50, 'PONTO', 'Registo de ponto', 'BIT', 'US',
        1, 1, 0, 0, '', '', 10,
        60, 10, '', 0,
        '', '', 2, -999999999, 999999999,
        '', 1, 50, 10,
