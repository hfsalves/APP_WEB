SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF COL_LENGTH('dbo.AL', 'PRECOMINRIGIDO') IS NULL
BEGIN
    ALTER TABLE dbo.AL
    ADD PRECOMINRIGIDO bit NOT NULL
        CONSTRAINT DF_AL_PRECOMINRIGIDO DEFAULT (0) WITH VALUES;
END;

IF COL_LENGTH('dbo.PR_OVERRIDE', 'ORIGEM') IS NULL
BEGIN
    ALTER TABLE dbo.PR_OVERRIDE
    ADD ORIGEM varchar(30) NOT NULL
        CONSTRAINT DF_PR_OVERRIDE_ORIGEM DEFAULT ('LEGADO') WITH VALUES;

    EXEC(N'
        UPDATE dbo.PR_OVERRIDE
        SET ORIGEM = ''ATENCAO_IMEDIATA''
        WHERE UPPER(LTRIM(RTRIM(ISNULL(MOTIVO, '''')))) = N''ATENÇÃO IMEDIATA'';
    ');
END;

IF NOT EXISTS (
    SELECT 1
    FROM dbo.CAMPOS
    WHERE UPPER(LTRIM(RTRIM(ISNULL(TABELA, '')))) = 'AL'
      AND UPPER(LTRIM(RTRIM(ISNULL(NMCAMPO, '')))) = 'PRECOMINRIGIDO'
)
BEGIN
    INSERT INTO dbo.CAMPOS (
        CAMPOSSTAMP, ORDEM, NMCAMPO, DESCRICAO, TIPO, TABELA,
        LISTA, FILTRO, ADMIN, RONLY, TAM, ORDEM_MOBILE, TAM_MOBILE,
        OBRIGATORIO, VISIVEL, ORDEM_LISTA, TAM_LISTA,
        ORDEM_LISTA_MOBILE, TAM_LISTA_MOBILE, LISTA_MOBILE_LABEL
    )
    VALUES (
        LEFT(REPLACE(CONVERT(varchar(36), NEWID()), '-', ''), 25),
        47, 'PRECOMINRIGIDO', 'Preço mínimo rígido', 'BIT', 'AL',
        0, 1, 0, 0, 5, 44, 10,
        0, 1, 0, 5, 0, 5, 'Preço mínimo rígido'
    );
END;

UPDATE dbo.CAMPOS
SET DESCRICAO = 'Preço mínimo rígido',
    TIPO = 'BIT',
    ORDEM = 47,
    TAM = 5,
    ORDEM_MOBILE = 44,
    TAM_MOBILE = 10,
    FILTRO = 1,
    RONLY = 0,
    VISIVEL = 1
WHERE UPPER(LTRIM(RTRIM(ISNULL(TABELA, '')))) = 'AL'
  AND UPPER(LTRIM(RTRIM(ISNULL(NMCAMPO, '')))) = 'PRECOMINRIGIDO';

COMMIT TRANSACTION;
