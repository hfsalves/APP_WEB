/* Histórico de sessões da aplicação e alterações de horas no turnover. */
IF OBJECT_ID('dbo.APP_SESSAO_LOG', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.APP_SESSAO_LOG (
        APPSESSAOSTAMP varchar(25) NOT NULL CONSTRAINT PK_APP_SESSAO_LOG PRIMARY KEY,
        LOGIN_TENTADO varchar(100) NOT NULL CONSTRAINT DF_APP_SESSAO_LOGIN DEFAULT '',
        USSTAMP varchar(25) NOT NULL CONSTRAINT DF_APP_SESSAO_USSTAMP DEFAULT '',
        NOME nvarchar(120) NOT NULL CONSTRAINT DF_APP_SESSAO_NOME DEFAULT '',
        FEID int NULL,
        SUCESSO bit NOT NULL CONSTRAINT DF_APP_SESSAO_SUCESSO DEFAULT 0,
        MOTIVO varchar(60) NOT NULL CONSTRAINT DF_APP_SESSAO_MOTIVO DEFAULT '',
        ENTRADA_UTC datetime2(3) NOT NULL CONSTRAINT DF_APP_SESSAO_ENTRADA DEFAULT SYSUTCDATETIME(),
        ULTIMA_ATIVIDADE_UTC datetime2(3) NULL,
        SAIDA_UTC datetime2(3) NULL,
        SAIDA_TIPO varchar(30) NOT NULL CONSTRAINT DF_APP_SESSAO_SAIDA_TIPO DEFAULT '',
        IP_ENTRADA varchar(64) NOT NULL CONSTRAINT DF_APP_SESSAO_IP DEFAULT '',
        IP_ULTIMO varchar(64) NOT NULL CONSTRAINT DF_APP_SESSAO_IP_ULTIMO DEFAULT '',
        USER_AGENT nvarchar(500) NOT NULL CONSTRAINT DF_APP_SESSAO_USER_AGENT DEFAULT '',
        ROTA_ENTRADA nvarchar(500) NOT NULL CONSTRAINT DF_APP_SESSAO_ROTA DEFAULT '',
        ULTIMA_ROTA nvarchar(500) NOT NULL CONSTRAINT DF_APP_SESSAO_ULTIMA_ROTA DEFAULT ''
    );
END;

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.APP_SESSAO_LOG') AND name='IX_APP_SESSAO_LOGIN_ENTRADA')
    CREATE INDEX IX_APP_SESSAO_LOGIN_ENTRADA ON dbo.APP_SESSAO_LOG (LOGIN_TENTADO, ENTRADA_UTC DESC);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.APP_SESSAO_LOG') AND name='IX_APP_SESSAO_ATIVAS')
    CREATE INDEX IX_APP_SESSAO_ATIVAS ON dbo.APP_SESSAO_LOG (SUCESSO, SAIDA_UTC, ULTIMA_ATIVIDADE_UTC DESC);

IF OBJECT_ID('dbo.TURNOVER_HORAS_LOG', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TURNOVER_HORAS_LOG (
        TURNOVERLOGSTAMP varchar(25) NOT NULL CONSTRAINT PK_TURNOVER_HORAS_LOG PRIMARY KEY,
        RSSTAMP varchar(25) NOT NULL CONSTRAINT DF_TURNOVER_LOG_RSSTAMP DEFAULT '',
        RESERVA varchar(80) NOT NULL CONSTRAINT DF_TURNOVER_LOG_RESERVA DEFAULT '',
        ALOJAMENTO nvarchar(120) NOT NULL CONSTRAINT DF_TURNOVER_LOG_ALOJAMENTO DEFAULT '',
        TIPO varchar(10) NOT NULL,
        DATA_MOVIMENTO date NULL,
        HORA_ANTERIOR varchar(5) NOT NULL CONSTRAINT DF_TURNOVER_LOG_HORA_ANT DEFAULT '',
        HORA_NOVA varchar(5) NOT NULL CONSTRAINT DF_TURNOVER_LOG_HORA_NOVA DEFAULT '',
        ACAO varchar(20) NOT NULL CONSTRAINT DF_TURNOVER_LOG_ACAO DEFAULT '',
        UTILIZADOR varchar(100) NOT NULL CONSTRAINT DF_TURNOVER_LOG_UTILIZADOR DEFAULT '',
        USSTAMP varchar(25) NOT NULL CONSTRAINT DF_TURNOVER_LOG_USSTAMP DEFAULT '',
        NOME nvarchar(120) NOT NULL CONSTRAINT DF_TURNOVER_LOG_NOME DEFAULT '',
        FEID int NULL,
        IP varchar(64) NOT NULL CONSTRAINT DF_TURNOVER_LOG_IP DEFAULT '',
        USER_AGENT nvarchar(500) NOT NULL CONSTRAINT DF_TURNOVER_LOG_USER_AGENT DEFAULT '',
        REQUEST_PATH nvarchar(500) NOT NULL CONSTRAINT DF_TURNOVER_LOG_PATH DEFAULT '',
        DTCRI_UTC datetime2(3) NOT NULL CONSTRAINT DF_TURNOVER_LOG_DTCRI DEFAULT SYSUTCDATETIME(),
        CONSTRAINT CK_TURNOVER_LOG_TIPO CHECK (TIPO IN ('CHECKIN', 'CHECKOUT'))
    );
END;

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.TURNOVER_HORAS_LOG') AND name='IX_TURNOVER_LOG_RESERVA')
    CREATE INDEX IX_TURNOVER_LOG_RESERVA ON dbo.TURNOVER_HORAS_LOG (RSSTAMP, DTCRI_UTC DESC);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.TURNOVER_HORAS_LOG') AND name='IX_TURNOVER_LOG_UTILIZADOR')
    CREATE INDEX IX_TURNOVER_LOG_UTILIZADOR ON dbo.TURNOVER_HORAS_LOG (UTILIZADOR, DTCRI_UTC DESC);
