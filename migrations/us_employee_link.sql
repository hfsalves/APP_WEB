/* GR360_CORE — ligação obrigatória da conta GR360 ao funcionário PHC (PE). */
SET XACT_ABORT ON;
GO
BEGIN TRANSACTION;

IF COL_LENGTH('dbo.US', 'PEFEID') IS NULL
BEGIN
    ALTER TABLE dbo.US
        ADD PEFEID int NOT NULL
            CONSTRAINT DF_US_PEFEID DEFAULT (0) WITH VALUES;
END;

IF COL_LENGTH('dbo.US', 'PEEMPRESA') IS NULL
BEGIN
    ALTER TABLE dbo.US
        ADD PEEMPRESA varchar(120) NOT NULL
            CONSTRAINT DF_US_PEEMPRESA DEFAULT ('') WITH VALUES;
END;

IF NOT EXISTS (
    SELECT 1
    FROM sys.indexes
    WHERE object_id = OBJECT_ID('dbo.US')
      AND name = 'IX_US_PEFEID_PENO'
)
BEGIN
    CREATE NONCLUSTERED INDEX IX_US_PEFEID_PENO
        ON dbo.US (PEFEID, PENO)
        INCLUDE (USSTAMP, LOGIN, NOME, INATIVO);
END;

COMMIT TRANSACTION;
GO
