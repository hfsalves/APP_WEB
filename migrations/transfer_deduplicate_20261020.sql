/*
  Remove the five repeated button submissions for HMH3A9BK3E while retaining
  the first request. A private archive makes the cleanup recoverable.
*/
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID('dbo.TRANSFERS_DEDUP_ARCHIVE', 'U') IS NULL
BEGIN
    SELECT TOP (0)
        T.*,
        CAST(NULL AS datetime2(0)) AS ARCHIVED_AT_UTC,
        CAST(NULL AS varchar(200)) AS ARCHIVE_REASON
    INTO dbo.TRANSFERS_DEDUP_ARCHIVE
    FROM dbo.TRANSFERS AS T;
END;

INSERT INTO dbo.TRANSFERS_DEDUP_ARCHIVE
SELECT T.*, SYSUTCDATETIME(), 'Submissão repetida pelo botão; mantido 77E053EC8207443D8FBA36DC0'
FROM dbo.TRANSFERS AS T
WHERE T.TRANSFERSTAMP IN (
    'E492505D0CD045958CBE87C7D',
    '0737AAE5CB864D6FABB6D8804',
    '3931C316A9C84869BD8A85B58',
    '3490D2122027435094BFDA7C9',
    '2544C33B94F74390982B40065'
)
AND NOT EXISTS (
    SELECT 1 FROM dbo.TRANSFERS_DEDUP_ARCHIVE AS A
    WHERE A.TRANSFERSTAMP = T.TRANSFERSTAMP
);

INSERT INTO dbo.EMAIL_LOG (EMAIL_ID, DATA_TENTATIVA, RESULTADO, MENSAGEM, SMTP_RESPONSE)
SELECT Q.ID, GETDATE(), 'CANCELADO',
       'Email duplicado cancelado durante a limpeza do pedido de transfer HMH3A9BK3E.', NULL
FROM dbo.EMAIL_QUEUE AS Q
WHERE Q.ID IN (10153, 10154)
  AND Q.ESTADO IN ('PENDENTE', 'A_ENVIAR', 'ERRO')
  AND NOT EXISTS (
      SELECT 1 FROM dbo.EMAIL_LOG AS L
      WHERE L.EMAIL_ID=Q.ID AND L.RESULTADO='CANCELADO'
        AND L.MENSAGEM LIKE '%HMH3A9BK3E%'
  );

UPDATE dbo.EMAIL_QUEUE
SET ESTADO='CANCELADO',
    ERRO_ULTIMA_TENTATIVA='Cancelado: submissão duplicada do pedido HMH3A9BK3E.'
WHERE ID IN (10153, 10154)
  AND ESTADO IN ('PENDENTE', 'A_ENVIAR', 'ERRO');

DELETE FROM dbo.TRANSFERS
WHERE TRANSFERSTAMP IN (
    'E492505D0CD045958CBE87C7D',
    '0737AAE5CB864D6FABB6D8804',
    '3931C316A9C84869BD8A85B58',
    '3490D2122027435094BFDA7C9',
    '2544C33B94F74390982B40065'
);

UPDATE dbo.TRANSFERS
SET REQUEST_HASH='87CBEE34E0418F8F5EA79263B9EA34DA0AE9CEE6FB97767A79DE004680FDE8C0',
    EMAIL_ESTADO=CASE WHEN EMAIL_ID IS NOT NULL THEN 'ENVIADO' ELSE EMAIL_ESTADO END,
    EMAIL_ERRO=NULL,
    DTALT=GETDATE()
WHERE TRANSFERSTAMP='77E053EC8207443D8FBA36DC0';

COMMIT TRANSACTION;
