/*
  Remove the 48 cancelled retries created by the old transfer button for
  HM4YP5J8DA. The valid first request remains active and every removed row is
  retained in the private recovery archive.
*/
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID('dbo.TRANSFERS_DEDUP_ARCHIVE', 'U') IS NULL
BEGIN
    SELECT TOP (0)
        T.*,
        CAST(NULL AS datetime2(0)) AS ARCHIVED_AT_UTC,
        CAST(NULL AS varchar(200)) AS ARCHIVE_REASON
    INTO dbo.TRANSFERS_DEDUP_ARCHIVE
    FROM dbo.TRANSFERS AS T;
END;

INSERT INTO dbo.TRANSFERS_DEDUP_ARCHIVE
SELECT
    T.*,
    SYSUTCDATETIME(),
    'Submissão repetida pelo botão; mantido 1EB8122138B04DEBB91D4E3AD'
FROM dbo.TRANSFERS AS T
WHERE T.RESERVA = 'HM4YP5J8DA'
  AND T.TRANSFERSTAMP <> '1EB8122138B04DEBB91D4E3AD'
  AND UPPER(LTRIM(RTRIM(ISNULL(T.ESTADO, '')))) IN ('CANCELADO', 'CANCELADA')
  AND NOT EXISTS (
      SELECT 1
      FROM dbo.TRANSFERS_DEDUP_ARCHIVE AS A
      WHERE A.TRANSFERSTAMP = T.TRANSFERSTAMP
  );

DELETE T
FROM dbo.TRANSFERS AS T
WHERE T.RESERVA = 'HM4YP5J8DA'
  AND T.TRANSFERSTAMP <> '1EB8122138B04DEBB91D4E3AD'
  AND UPPER(LTRIM(RTRIM(ISNULL(T.ESTADO, '')))) IN ('CANCELADO', 'CANCELADA');

COMMIT TRANSACTION;
