    ALTER TABLE dbo.PB_STRIPE_TEST_PAYMENTS ADD CAMBIO_BASE decimal(18, 8) NULL;
IF COL_LENGTH('dbo.PB_STRIPE_TEST_PAYMENTS', 'FX_MARGIN_PERCENT') IS NULL
    ALTER TABLE dbo.PB_STRIPE_TEST_PAYMENTS ADD FX_MARGIN_PERCENT decimal(9, 4) NULL;
