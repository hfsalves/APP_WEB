SET R.MOEDA_PAGAMENTO = COALESCE(R.MOEDA_PAGAMENTO, P.MOEDA),
    R.VALOR_PAGAMENTO = COALESCE(R.VALOR_PAGAMENTO, P.VALOR),
    R.CAMBIO_PAGAMENTO = COALESCE(R.CAMBIO_PAGAMENTO, P.CAMBIO),
    R.STRIPE_PAYMENT_INTENT = COALESCE(R.STRIPE_PAYMENT_INTENT, P.PAYMENT_INTENT_ID),
    R.STRIPE_CHARGE_ID = COALESCE(R.STRIPE_CHARGE_ID, P.CHARGE_ID),
    R.STRIPE_BALANCE_TRANSACTION = COALESCE(R.STRIPE_BALANCE_TRANSACTION, P.BALANCE_TRANSACTION_ID),
    R.STRIPE_LIQUIDO = COALESCE(R.STRIPE_LIQUIDO, P.STRIPE_LIQUIDO),
    R.STRIPE_LIQUIDO_MOEDA = COALESCE(R.STRIPE_LIQUIDO_MOEDA, P.STRIPE_LIQUIDO_MOEDA)
FROM dbo.RS AS R
INNER JOIN dbo.PB_STRIPE_TEST_PAYMENTS AS P ON P.RSSTAMP = R.RSSTAMP
WHERE ISNULL(R.ORIGEM, '') = 'PORTOBREAK';

