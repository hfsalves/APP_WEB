UPDATE dbo.PB_BOOKING_REQUESTS
SET VALOR_APRESENTADO = COALESCE(VALOR_APRESENTADO, PRECO_ESTIMADO),
    CAMBIO_APRESENTACAO = COALESCE(CAMBIO_APRESENTACAO, 1),
    CAMBIO_BASE = COALESCE(CAMBIO_BASE, 1),
    FX_MARGIN_PERCENT = COALESCE(FX_MARGIN_PERCENT, 0)
