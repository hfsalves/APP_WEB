SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID('dbo.PB_FX_RATES', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.PB_FX_RATES (
        MOEDA char(3) NOT NULL,
        TAXA_POR_EUR decimal(18, 8) NOT NULL,
        DATA_TAXA date NOT NULL,
        ATUALIZADO_EM datetime2(0) NOT NULL,
        FONTE varchar(120) NOT NULL,
        ATIVA bit NOT NULL CONSTRAINT DF_PB_FX_RATES_ATIVA DEFAULT 1,
        ULTIMO_ERRO varchar(1000) NULL,
        CONSTRAINT PK_PB_FX_RATES PRIMARY KEY CLUSTERED (MOEDA),
        CONSTRAINT CK_PB_FX_RATES_MOEDA CHECK (MOEDA IN ('EUR', 'GBP', 'USD')),
        CONSTRAINT CK_PB_FX_RATES_TAXA CHECK (TAXA_POR_EUR > 0)
    );
END;

IF NOT EXISTS (SELECT 1 FROM dbo.PARA WHERE UPPER(LTRIM(RTRIM(PARAMETRO))) = 'FX_MARGIN_PERCENT')
BEGIN
    INSERT INTO dbo.PARA
        (PARASTAMP, PARAMETRO, DESCRICAO, TIPO, CVALOR, DVALOR, NVALOR, LVALOR, GRUPO, FEID)
    VALUES
