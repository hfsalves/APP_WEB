         'FX_MARGIN_PERCENT', 'Margem cambial PortoBreak (%)', 'NUMERICO', '1.5',
         '19000101', 1.5000, 0, 'PORTOBREAK', NULL);
END;

IF COL_LENGTH('dbo.PB_BOOKING_REQUESTS', 'MOEDA_APRESENTACAO') IS NULL
    ALTER TABLE dbo.PB_BOOKING_REQUESTS ADD MOEDA_APRESENTACAO char(3) NOT NULL CONSTRAINT DF_PB_BOOKING_MOEDA DEFAULT 'EUR' WITH VALUES;
