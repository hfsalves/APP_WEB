/* Recoverable manual editing/deletion support for the transfer dashboard. */
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID('dbo.TRANSFERS_ARCHIVE', 'U') IS NULL
BEGIN
    SELECT TOP (0)
        T.*,
        CAST(NULL AS datetime2(0)) AS ARCHIVED_AT_UTC,
        CAST(NULL AS varchar(60)) AS ARCHIVED_BY,
        CAST(NULL AS varchar(250)) AS ARCHIVE_REASON
    INTO dbo.TRANSFERS_ARCHIVE
    FROM dbo.TRANSFERS AS T;
END;

IF OBJECT_ID('dbo.TRANSFERS_AUDIT', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TRANSFERS_AUDIT (
        ID bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_TRANSFERS_AUDIT PRIMARY KEY,
        TRANSFERSTAMP varchar(25) NOT NULL,
        ACAO varchar(20) NOT NULL,
        DADOS_ANTES nvarchar(max) NULL,
        DADOS_DEPOIS nvarchar(max) NULL,
        UTILIZADOR varchar(60) NOT NULL,
        DTCRI datetime2(0) NOT NULL CONSTRAINT DF_TRANSFERS_AUDIT_DTCRI DEFAULT SYSUTCDATETIME()
    );
    CREATE INDEX IX_TRANSFERS_AUDIT_TRANSFERSTAMP
        ON dbo.TRANSFERS_AUDIT (TRANSFERSTAMP, DTCRI DESC);
END;

COMMIT TRANSACTION;
