SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF COL_LENGTH('dbo.AL', 'TAXATURPERIODO') IS NULL
BEGIN
    ALTER TABLE dbo.AL
    ADD TAXATURPERIODO varchar(12) NOT NULL
        CONSTRAINT DF_AL_TAXATURPERIODO DEFAULT ('Trimestral') WITH VALUES;

    EXEC(N'
        UPDATE dbo.AL
        SET TAXATURPERIODO = ''Mensal''
        WHERE UPPER(LTRIM(RTRIM(ISNULL(NOME, '''')))) IN
            (''SUNNY'', ''BALCONY'', ''CASA DA PRAÇA'', ''CASA DO CRASTO'', ''GREEN HOUSE'');
    ');
END;

IF NOT EXISTS (
    SELECT 1 FROM sys.check_constraints
    WHERE parent_object_id = OBJECT_ID('dbo.AL')
      AND name = 'CK_AL_TAXATURPERIODO'
)
BEGIN
    EXEC(N'
        ALTER TABLE dbo.AL WITH CHECK
        ADD CONSTRAINT CK_AL_TAXATURPERIODO
        CHECK (TAXATURPERIODO IN (''Mensal'', ''Trimestral''));
    ');
END;

IF NOT EXISTS (
    SELECT 1 FROM dbo.CAMPOS
    WHERE UPPER(LTRIM(RTRIM(ISNULL(TABELA, '')))) = 'AL'
      AND UPPER(LTRIM(RTRIM(ISNULL(NMCAMPO, '')))) = 'TAXATURPERIODO'
)
BEGIN
    INSERT INTO dbo.CAMPOS (
        CAMPOSSTAMP, ORDEM, NMCAMPO, DESCRICAO, TIPO, TABELA,
        LISTA, FILTRO, ADMIN, RONLY, COMBO, VIRTUAL, TAM,
        ORDEM_MOBILE, TAM_MOBILE, CONDICAO_VISIVEL, OBRIGATORIO,
        VISIVEL, ORDEM_LISTA, TAM_LISTA, ORDEM_LISTA_MOBILE,
        TAM_LISTA_MOBILE, LISTA_MOBILE_LABEL
    ) VALUES (
        LEFT(REPLACE(CONVERT(varchar(36), NEWID()), '-', ''), 25),
        48, 'TAXATURPERIODO', 'Entrega taxa turística', 'COMBO', 'AL',
        0, 1, 0, 0,
        'SELECT ''Mensal'' UNION ALL SELECT ''Trimestral''', '', 10,
        45, 10, '', 0,
        1, 0, 5, 0, 5, 'Entrega taxa turística'
    );
END;

UPDATE dbo.CAMPOS
SET ORDEM = 48,
    DESCRICAO = 'Entrega taxa turística',
    TIPO = 'COMBO',
    COMBO = 'SELECT ''Mensal'' UNION ALL SELECT ''Trimestral''',
    TAM = 10,
    ORDEM_MOBILE = 45,
    TAM_MOBILE = 10,
    FILTRO = 1,
    RONLY = 0,
    VISIVEL = 1,
    LISTA_MOBILE_LABEL = 'Entrega taxa turística'
WHERE UPPER(LTRIM(RTRIM(ISNULL(TABELA, '')))) = 'AL'
  AND UPPER(LTRIM(RTRIM(ISNULL(NMCAMPO, '')))) = 'TAXATURPERIODO';

IF NOT EXISTS (
    SELECT 1 FROM dbo.MENU
    WHERE MENUSTAMP = 'TAXTURMENU00000000000001'
       OR UPPER(LTRIM(RTRIM(ISNULL(TABELA, '')))) = 'TAXAS_TURISTICAS'
)
BEGIN
    INSERT INTO dbo.MENU
        (MENUSTAMP, ORDEM, NOME, TABELA, URL, ADMIN, ICONE, FORM, NOVO, [ORDERBY], INATIVO)
    VALUES
        ('TAXTURMENU00000000000001', 213, 'Taxas Turísticas', 'TAXAS_TURISTICAS',
         '/guestspa/taxas-turisticas', 0, 'fa-solid fa-bed', '', 1, '', 0);
END;
ELSE
BEGIN
    UPDATE dbo.MENU
    SET ORDEM = 213,
        NOME = 'Taxas Turísticas',
        TABELA = 'TAXAS_TURISTICAS',
        URL = '/guestspa/taxas-turisticas',
        ICONE = 'fa-solid fa-bed',
        INATIVO = 0
    WHERE MENUSTAMP = 'TAXTURMENU00000000000001'
       OR UPPER(LTRIM(RTRIM(ISNULL(TABELA, '')))) = 'TAXAS_TURISTICAS';
END;

IF OBJECT_ID('dbo.MOD_OBJETOS', 'U') IS NOT NULL
BEGIN
    INSERT INTO dbo.MOD_OBJETOS
        (MODOBJSTAMP, MODSTAMP, TIPO, OBJKEY, OBJNOME, OBJROTA, MENUSTAMP,
         ORDEM, ATIVO, DTCRI, USERCRIACAO, USERALTERACAO)
    SELECT
        LEFT(REPLACE(CONVERT(varchar(36), NEWID()), '-', ''), 25),
        source.MODSTAMP,
        'MENU',
        'MENU:TAXTURMENU00000000000001',
        'Taxas Turísticas',
        '/guestspa/taxas-turisticas',
        'TAXTURMENU00000000000001',
        213,
        1,
        GETDATE(),
        'codex',
        ''
    FROM dbo.MOD_OBJETOS AS source
    WHERE source.MENUSTAMP = '34BA0790-C450-4684-A388-5'
      AND ISNULL(source.ATIVO, 0) = 1
      AND NOT EXISTS (
          SELECT 1 FROM dbo.MOD_OBJETOS existing
          WHERE existing.MODSTAMP = source.MODSTAMP
            AND existing.OBJKEY = 'MENU:TAXTURMENU00000000000001'
      );
END;

INSERT INTO dbo.ACESSOS
    (ACESSOSSTAMP, UTILIZADOR, TABELA, CONSULTAR, INSERIR, EDITAR, ELIMINAR, USSTAMP, FEID)
SELECT
    LEFT(REPLACE(CONVERT(varchar(36), NEWID()), '-', ''), 25),
    LTRIM(RTRIM(U.LOGIN)),
    'TAXAS_TURISTICAS',
    1, 0, 0, 0,
    U.USSTAMP,
    2
FROM dbo.US U
WHERE (ISNULL(U.ADMIN, 0) = 1 OR ISNULL(U.DEV, 0) = 1)
  AND ISNULL(U.INATIVO, 0) = 0
  AND LTRIM(RTRIM(ISNULL(U.LOGIN, ''))) <> ''
  AND NOT EXISTS (
      SELECT 1 FROM dbo.ACESSOS A
      WHERE LOWER(LTRIM(RTRIM(ISNULL(A.UTILIZADOR, '')))) = LOWER(LTRIM(RTRIM(U.LOGIN)))
        AND UPPER(LTRIM(RTRIM(ISNULL(A.TABELA, '')))) = 'TAXAS_TURISTICAS'
  );

IF OBJECT_ID('dbo.GUESTSPA_TOURIST_TAX_AUDIT', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.GUESTSPA_TOURIST_TAX_AUDIT (
        AUDITSTAMP varchar(25) NOT NULL CONSTRAINT PK_GUESTSPA_TOURIST_TAX_AUDIT PRIMARY KEY,
        UTILIZADOR varchar(60) NOT NULL CONSTRAINT DF_GSTTA_UTILIZADOR DEFAULT (''),
        PERIODO varchar(20) NOT NULL CONSTRAINT DF_GSTTA_PERIODO DEFAULT (''),
        TIPO varchar(20) NOT NULL CONSTRAINT DF_GSTTA_TIPO DEFAULT (''),
        DATA_INI date NULL,
        DATA_FIM date NULL,
        FEID int NULL,
        ACAO varchar(20) NOT NULL CONSTRAINT DF_GSTTA_ACAO DEFAULT (''),
        FILTROS nvarchar(500) NOT NULL CONSTRAINT DF_GSTTA_FILTROS DEFAULT (N''),
        DTCRIACAO_UTC datetime2(0) NOT NULL CONSTRAINT DF_GSTTA_DTCRI DEFAULT (SYSUTCDATETIME())
    );
END;

IF COL_LENGTH('dbo.GUESTSPA_TOURIST_TAX_AUDIT', 'TIPO') IS NULL
    EXEC(N'ALTER TABLE dbo.GUESTSPA_TOURIST_TAX_AUDIT ADD TIPO varchar(20) NOT NULL CONSTRAINT DF_GSTTA_TIPO DEFAULT ('''') WITH VALUES;');
IF COL_LENGTH('dbo.GUESTSPA_TOURIST_TAX_AUDIT', 'DATA_INI') IS NULL
    EXEC(N'ALTER TABLE dbo.GUESTSPA_TOURIST_TAX_AUDIT ADD DATA_INI date NULL;');
IF COL_LENGTH('dbo.GUESTSPA_TOURIST_TAX_AUDIT', 'DATA_FIM') IS NULL
    EXEC(N'ALTER TABLE dbo.GUESTSPA_TOURIST_TAX_AUDIT ADD DATA_FIM date NULL;');
IF COL_LENGTH('dbo.GUESTSPA_TOURIST_TAX_AUDIT', 'FEID') IS NULL
    EXEC(N'ALTER TABLE dbo.GUESTSPA_TOURIST_TAX_AUDIT ADD FEID int NULL;');
IF COL_LENGTH('dbo.GUESTSPA_TOURIST_TAX_AUDIT', 'FILTROS') IS NULL
    EXEC(N'ALTER TABLE dbo.GUESTSPA_TOURIST_TAX_AUDIT ADD FILTROS nvarchar(500) NOT NULL CONSTRAINT DF_GSTTA_FILTROS DEFAULT (N'''') WITH VALUES;');

COMMIT TRANSACTION;
